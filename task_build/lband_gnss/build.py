    s.page_width=Cm(21); s.page_height=Cm(29.7)
    s.top_margin=Cm(2.1); s.bottom_margin=Cm(2.0); s.left_margin=Cm(2.2); s.right_margin=Cm(2.2)
    s.header_distance=Cm(0.9); s.footer_distance=Cm(0.9)
    for name in ['Normal','Body Text','First Paragraph','Compact']:
        if name not in d.styles: d.styles.add_style(name,1)
        st=d.styles[name]; set_font(st)
        st.paragraph_format.line_spacing=1.24; st.paragraph_format.space_after=Pt(5)
