def qa_pdfs():
    result={}
    if shutil.which('libreoffice'):
        for p in DOCS.glob('*.docx'):
            cmd=['libreoffice','-env:UserInstallation=file:///tmp/lo_lband_profile','--headless','--convert-to','pdf','--outdir',str(DOCS),str(p)]
            proc=subprocess.run(cmd,capture_output=True,text=True,timeout=160)
            pdf=p.with_suffix('.pdf')
            if pdf.exists():
                z=fitz.open(pdf); empties=[];outside=[]
                for j,page in enumerate(z):
                    if len(page.get_text().strip())<10:empties.append(j+1)
                    for b in page.get_text('blocks'):
                        if b[0]<-2 or b[1]<-2 or b[2]>page.rect.width+2 or b[3]>page.rect.height+2:outside.append(j+1)
                result[p.name]={'pdf_pages':len(z),'nearly_empty_pages':empties,'text_outside_page':sorted(set(outside))}
                shutil.copy2(pdf,PUB/pdf.name)
                # Diagnostic render, no claims of human visual inspection.
                q=OUT/'04_排版检查';q.mkdir(exist_ok=True)
                for j in sorted(set([0,min(2,len(z)-1),len(z)-1])):
                    z[j].get_pixmap(matrix=fitz.Matrix(0.75,0.75)).save(q/f'{p.stem}_page{j+1}.png')
            else: result[p.name]={'pdf_error':proc.stderr[-1500:]+proc.stdout[-1500:]}
    else: result['note']='LibreOffice unavailable; DOCX structure check only.'
    return result


