def polish_docx(path):
    d=Document(path)
    for table in d.tables:
        table.autofit=False
        n=len(table.columns); usable=16.6/n
        for row_idx,row in enumerate(table.rows):
            pr=row._tr.get_or_add_trPr(); no=OxmlElement('w:cantSplit'); pr.append(no)
            if row_idx==0:
                hd=OxmlElement('w:tblHeader'); pr.append(hd)
            for cell in row.cells:
                cell.width=Cm(usable)
                tcpr=cell._tc.get_or_add_tcPr()
                marg=OxmlElement('w:tcMar')
                for edge in ['top','left','bottom','right']:
                    z=OxmlElement('w:'+edge);z.set(qn('w:w'),'85');z.set(qn('w:type'),'dxa');marg.append(z)
                tcpr.append(marg)
                if row_idx==0:
                    shade=OxmlElement('w:shd');shade.set(qn('w:fill'),'E9EFF6');tcpr.append(shade)
                for p in cell.paragraphs:
                    p.paragraph_format.line_spacing=1.12;p.paragraph_format.space_after=Pt(2)
                    for r in p.runs:
                        r.font.size=Pt(9)
                        if row_idx==0:r.font.bold=True
    # Native editable equations are generated by pandoc. Preserve them.
    settings=d.settings.element
    upd=OxmlElement('w:updateFields');upd.set(qn('w:val'),'true');settings.append(upd)
    d.core_properties.title='L波段天基雷达对卫星导航接收机详细干扰分析实施方案' if 'Detailed' in path.name else 'L波段雷达对GNSS干扰论文导读与下载记录'
    d.core_properties.subject='公开技术方法整理；实际项目数据未提供；不构成已完成兼容性结论'
    d.save(path)
    with zipfile.ZipFile(path) as z:
        x=z.read('word/document.xml').decode()
    return {'paragraphs':len(d.paragraphs),'tables':len(d.tables),'equation_elements':x.count('<m:oMath>'),'bytes':path.stat().st_size,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}


def convert(md, name):
    out=DOCS/name
    pypandoc.convert_file(str(md),'docx',format='markdown+tex_math_dollars',outputfile=str(out),extra_args=['--standalone','--toc','--toc-depth=2','--reference-doc='+str(BASE/'reference.docx')])
    info=polish_docx(out)
    shutil.copy2(out,PUB/out.name)
    return out,info


def fetch_pdf(item):
    result=dict(item); result.update(status='未取得PDF',local_file='',pages=0,bytes=0,sha256='',resolved_url='',attempts=[])
    candidates=list(item.get('pdf_urls',[]))
    s=requests.Session();s.headers.update(SESSION_HEADERS)
    # Follow only publisher/repository links. No paywall, authentication or anti-bot bypass.
    if not candidates:
        try:
            r=s.get(item['page_url'],timeout=(15,40));r.raise_for_status();soup=BeautifulSoup(r.text,'html.parser')
            for m in soup.select('meta[name="citation_pdf_url"]'):
                if m.get('content'):candidates.append(urljoin(r.url,m['content']))
            for a in soup.find_all('a',href=True):
                u=urljoin(r.url,a['href']);label=a.get_text(' ',strip=True)
                if ('.pdf' in u.lower() or 'downloadarticlefile' in u.lower() or 'download' in u.lower() and 'pdf' in label.lower()) and not u.lower().startswith('javascript:'):
                    candidates.append(u)
        except Exception as e:result['attempts'].append({'url':item['page_url'],'error':str(e)[:200]})
    for url in list(dict.fromkeys(candidates))[:4]:
        for retry in range(2):
            try:
                r=s.get(url,timeout=(15,65));r.raise_for_status();data=r.content
                if not data.lstrip().startswith(b'%PDF-'):raise ValueError('响应不是PDF；未保存网页或登录页')
                pdf=fitz.open(stream=data,filetype='pdf')
                if pdf.page_count<2 or pdf.needs_pass:raise ValueError('PDF页数不足或加密')
                text='\n'.join(pdf[i].get_text() for i in range(min(4,pdf.page_count))).lower()
                matches=sum(t.lower() in text for t in item.get('expected_terms',[]))
                if item.get('expected_terms') and matches<min(2,len(item['expected_terms'])):raise ValueError('题名/作者关键词未通过检查')
                folder=PAPERS/item['group'];folder.mkdir(exist_ok=True)
                p=folder/item['filename'];p.write_bytes(data)
                result.update(status='已下载并通过PDF结构和关键词检查',local_file=str(p.relative_to(OUT)),pages=pdf.page_count,bytes=len(data),sha256=hashlib.sha256(data).hexdigest(),resolved_url=r.url)
                print('DOWNLOADED',item['id'],len(data),pdf.page_count,flush=True);return result
            except Exception as e:
                result['attempts'].append({'url':url,'attempt':retry+1,'error':str(e)[:250]})
                if hasattr(e,'response') and e.response is not None and e.response.status_code in (401,403,404):break
                if retry==0:time.sleep(1)
    print('NOT_DOWNLOADED',item['id'],result['attempts'],flush=True);return result


